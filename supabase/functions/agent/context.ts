export function pickModules(message: string, history: any[] = []) {
  const lastBot = String([...history].reverse().find((h: any) => h?.role === "assistant")?.content ?? "");
  const lastUser = String([...history].reverse().find((h: any) => h?.role === "user")?.content ?? "");
  // 이번 말 + 바로 앞 물꼬 답의 카드 · 앞 학생 말 (카드 답 · 이어서 하는 말도 같은 흐름으로)
  const text = `${message}\n${lastUser.slice(0, 300)}\n${(lastBot.match(/\[\[[^\]]*\]\]/g) ?? []).join(" ")}\n${lastBot.slice(0, 400)}`;
  const set = new Set(MOD_ORDER.filter((k) => MOD_RE[k].test(text)));
  return MOD_ORDER.filter((k) => set.has(k));
}
